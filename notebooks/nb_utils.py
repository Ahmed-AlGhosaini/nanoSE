def load_metrics(run_dir: str | os.PathLike):
    """
    Returns a DataFrame of the per-epoch validation metrics of one run, with the
    cumulative wall-clock time joined in when ``progress.json`` is available.
    """
    import pandas as pd

    run_dir = Path(run_dir)
    path = run_dir / "validation_metrics.jsonl"
    if not path.exists():
        return pd.DataFrame()
    records = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    frame = pd.DataFrame(records)

    progress_path = run_dir / "progress.json"
    if progress_path.exists():
        progress = pd.DataFrame(json.loads(progress_path.read_text(encoding="utf-8")))
        if not progress.empty:
            progress = progress[["epoch", "loss", "train_si_sdr", "time"]]
            frame = frame.merge(progress, on="epoch", how="left")
            frame["time"] = frame["time"].fillna(0.0)
            frame["cumulative_time_min"] = frame["time"].cumsum() / 60.0
    frame["run"] = run_dir.name
    return frame


def load_config(run_dir: str | os.PathLike) -> dict:
    """Reads back the archived ``config.py`` of a run as a plain dict."""
    from models.crn import CRN, CRNTiny  # noqa: F401

    path = Path(run_dir) / "config.py"
    if not path.exists():
        return {}
    namespace: dict = {}
    exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), namespace, namespace)
    return {k: v for k, v in namespace.items() if not k.startswith("__")}


def summarize(run_dirs, labels=None, best_epoch: bool = True):
    """One row per run: the best (or last) epoch plus the key hyperparameters."""
    import pandas as pd

    rows = []
    for index, run_dir in enumerate(run_dirs):
        run_dir = Path(run_dir)
        frame = load_metrics(run_dir)
        config = load_config(run_dir)
        if frame.empty:
            continue
        trained = frame[frame["epoch"] > 0]
        if trained.empty:
            trained = frame
        selected = (
            trained.loc[trained["val_si_sdr"].idxmax()] if best_epoch else trained.iloc[-1]
        )
        model = config.get("model")
        row = {
            "label": labels[index] if labels else run_dir.name,
            "model": type(model).__name__ if model is not None else "N/A",
            "activation": getattr(model, "activation_name", "leaky_relu"),
            "lr": config.get("lr"),
            "batch_size": config.get("batch_size"),
            "epochs": config.get("epochs"),
            "remix": config.get("remix"),
            "epoch": int(selected["epoch"]),
            "val_si_sdr": selected["val_si_sdr"],
            "pesq": selected["pesq"],
            "estoi": selected["estoi"],
            "dnsmos": selected["dnsmos"],
        }
        if "cumulative_time_min" in selected:
            row["time_min"] = selected["cumulative_time_min"]
        rows.append(row)
    return pd.DataFrame(rows).sort_values("val_si_sdr", ascending=False).reset_index(drop=True)


def time_to_reach(run_dir, target_si_sdr: float):
    """Minutes of training needed to first reach `target_si_sdr` (NaN if never)."""
    frame = load_metrics(run_dir)
    if frame.empty or "cumulative_time_min" not in frame:
        return float("nan")
    reached = frame[(frame["epoch"] > 0) & (frame["val_si_sdr"] >= target_si_sdr)]
    return float(reached["cumulative_time_min"].iloc[0]) if not reached.empty else float("nan")


REGISTRY_PATH = Path("notebooks/experiment_runs.json")


def registry() -> dict:
    """The run directories recorded by the notebooks so far, keyed by short name."""
    if REGISTRY_PATH.exists():
        return json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    return {}


def remember(key: str, run_dir) -> Path:
    """Records a run directory so that later notebooks can pick it up."""
    entries = registry()
    entries[key] = str(run_dir).replace("\\", "/")
    REGISTRY_PATH.parent.mkdir(parents=True, exist_ok=True)
    REGISTRY_PATH.write_text(json.dumps(entries, indent=2, sort_keys=True), encoding="utf-8")
    return Path(entries[key])


def recall(key: str, default=None):
    """Looks up a run directory recorded with `remember`; falls back to `default`."""
    entry = registry().get(key)
    if entry is None:
        return default
    path = Path(entry)
    return path if path.exists() else default


def find_runs(pattern: str = "*", runs_dir: str = "runs"):
    """Run directories that contain metrics, newest last."""
    candidates = sorted(Path(runs_dir).glob(pattern))
    return [p for p in candidates if (p / "validation_metrics.jsonl").exists()]


def latest_run(name: str, runs_dir: str = "runs"):
    """The most recent run directory whose config `name` matches, or None."""
    matches = find_runs(f"*{name}*", runs_dir)
    return matches[-1] if matches else None


