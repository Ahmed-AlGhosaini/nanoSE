_CONFIG_TEMPLATE = '''"""{docstring}

Generated by the nanoSE homework notebooks -- edit the notebook, not this file.
"""

{imports}

# Log folder identifier name
name = "{name}"

# Training settings
{settings}

# Model definition
model = {model}
'''

_DEFAULTS = dict(
    epochs=25,
    batch_size=32,
    lr=1e-3,
    wd=0.02,
    compile=False,
    seed=42,
    remix=False,
)


def write_config(
    filename: str,
    *,
    name: str,
    model: str = "CRNTiny()",
    imports: str = "from models.crn import CRNTiny",
    docstring: str = "nanoSE experiment configuration.",
    directory: str = "config",
    **overrides,
) -> Path:
    """
    Writes a ``config/*.py`` file in the exact style of ``config/default_config.py``.

    `model` is written verbatim as a Python expression, so
    ``write_config(..., model='CRNTiny(activation="prelu")')`` is the way to
    configure the model itself. Unknown keyword arguments become extra config
    variables (e.g. ``warmup_steps=100``).
    """
    settings = dict(_DEFAULTS)
    settings.update(overrides)

    lines = []
    for key, value in settings.items():
        lines.append(f"{key} = {value!r}")

    path = Path(directory) / filename
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        _CONFIG_TEMPLATE.format(
            docstring=docstring,
            imports=imports,
            name=name,
            settings="\n".join(lines),
            model=model,
        ),
        encoding="utf-8",
    )
    return path


