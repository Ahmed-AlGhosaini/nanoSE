"""
Shared helpers for the nanoSE homework notebooks.

The notebooks drive the *unmodified* command line workflow of the repository
(``python train.py --config ...`` / ``python create_report.py ...``); everything
in here is glue: writing config files, launching training as a subprocess while
streaming its output into the notebook, and reading the logs back for analysis.
"""

