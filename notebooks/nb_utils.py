_REPO_MARKERS = ("train.py", "create_report.py", "models")


def in_colab() -> bool:
    return "google.colab" in sys.modules


def find_repo_root(start: str | os.PathLike | None = None) -> Path:
    """Walks upwards from `start` (or the cwd) until the nanoSE root is found."""
    here = Path(start or os.getcwd()).resolve()
    for candidate in (here, *here.parents):
        if all((candidate / marker).exists() for marker in _REPO_MARKERS):
            return candidate
    raise RuntimeError(
        f"Could not locate the nanoSE repository root starting from {here}. "
        "Run the notebook from inside a clone of the repository."
    )


def bootstrap(verbose: bool = True) -> Path:
    """
    Makes the notebook behave like a shell sitting in the repository root:
    changes the working directory there and puts it on ``sys.path``.
    Returns the repository root.
    """
    root = find_repo_root()
    os.chdir(root)
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))
    if verbose:
        print(f"Repository root: {root}")
        print(describe_device())
        _warn_if_unpatched()
    return root


def describe_device() -> str:
    import torch

    if torch.cuda.is_available():
        name = torch.cuda.get_device_name(0)
        mem = torch.cuda.get_device_properties(0).total_memory / 1e9
        return f"torch {torch.__version__} | CUDA GPU: {name} ({mem:.1f} GB)"
    if getattr(torch.backends, "mps", None) and torch.backends.mps.is_available():
        return f"torch {torch.__version__} | Apple MPS GPU"
    return (
        f"torch {torch.__version__} | CPU only ({torch.get_num_threads()} threads) "
        "-- full-scale training will be very slow, use a GPU runtime"
    )


def _warn_if_unpatched() -> None:
    """The notebooks need the homework modifications to models/crn.py."""
    try:
        from models.crn import get_activation  # noqa: F401
    except ImportError:
        print(
            "WARNING: models/crn.py does not expose get_activation(). This clone is "
            "the upstream version; the activation / loss experiments will not run. "
            "Clone the fork that contains the homework modifications."
        )


