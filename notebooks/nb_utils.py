_RUN_DIR_RE = re.compile(r"Copied config file to log folder:\s*(\S+)/config\.py")
_EPOCH_RE = re.compile(
    r"Epoch\s+(?P<epoch>\d+)/(?P<total>\d+)\s*\|\s*"
    r"Loss:\s*(?P<loss>[-\d.eE+]+).*?"
    r"Train SI-SDR:\s*(?P<train_si_sdr>[-\d.]+)dB\s*\|\s*"
    r"Val SI-SDR:\s*(?P<val_si_sdr>[-\d.]+)dB\s*\|\s*"
    r"PESQ:\s*(?P<pesq>[-\d.]+)\s*\|\s*STOI:\s*(?P<estoi>[-\d.]+)\s*\|\s*"
    r"DNSMOS:\s*(?P<dnsmos>[-\d.]+)\s*\|\s*Time:\s*(?P<time>[-\d.]+)s"
)


def parse_train_log(text: str) -> list[dict]:
    """Extracts one record per finished epoch from captured training output."""
    records = []
    for match in _EPOCH_RE.finditer(text):
        record = {k: float(v) for k, v in match.groupdict().items()}
        record["epoch"] = int(record["epoch"])
        record["total"] = int(record["total"])
        records.append(record)
    return records


def _stream_output(process, echo: bool = True, width: int = 160) -> str:
    """
    Reads the child process output, splitting on both newlines and carriage
    returns so tqdm progress bars refresh in place instead of flooding the cell.
    """
    chunks: list[str] = []
    buffer = ""
    while True:
        data = process.stdout.read(256)
        if not data:
            break
        chunks.append(data)
        buffer += data
        while True:
            match = re.search(r"[\r\n]", buffer)
            if match is None:
                break
            line, buffer = buffer[: match.start()], buffer[match.end() :]
            if not echo or not line.strip():
                continue
            if match.group(0) == "\n":
                print(line, flush=True)
            else:  # progress bar refresh
                print("\r" + line[:width].ljust(width), end="", flush=True)
    if buffer.strip():
        chunks.append("\n")
        if echo:
            print(buffer, flush=True)
    return "".join(chunks)


def run_training(
    config_path: str | os.PathLike,
    extra_args: tuple | list = (),
    echo: bool = True,
    progress_bars: bool = True,
) -> Path:
    """
    Runs ``python train.py --config <config_path>`` and returns the run directory.

    Alongside the artifacts written by ``train.py`` the run directory also gets
    ``train_log.txt`` (full captured output), ``progress.json`` (per-epoch
    metrics *and wall-clock time*, used by the speed analysis) and
    ``timing.json`` (total wall time).
    """
    config_path = Path(config_path)
    cmd = [sys.executable, "train.py", "--config", str(config_path), *map(str, extra_args)]
    print("$ " + " ".join(cmd[1:]))

    env = dict(os.environ, PYTHONUNBUFFERED="1")
    if not progress_bars:
        env["TQDM_DISABLE"] = "1"

    started = time.time()
    process = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
        env=env,
    )
    output = _stream_output(process, echo=echo)
    process.wait()
    elapsed = time.time() - started

    if process.returncode != 0:
        raise RuntimeError(
            f"Training failed with exit code {process.returncode}. "
            "The captured output is printed above."
        )

    match = _RUN_DIR_RE.search(output)
    if match is None:
        raise RuntimeError("Could not determine the run directory from the output.")
    run_dir = Path(match.group(1))

    (run_dir / "train_log.txt").write_text(output, encoding="utf-8")
    records = parse_train_log(output)
    (run_dir / "progress.json").write_text(json.dumps(records, indent=2), encoding="utf-8")
    (run_dir / "timing.json").write_text(
        json.dumps({"total_wall_time_s": elapsed, "config": str(config_path)}, indent=2),
        encoding="utf-8",
    )
    print(f"\nRun directory: {run_dir}  (total wall time {elapsed / 60:.1f} min)")
    return run_dir


def create_report(run_dirs, output: str = "report/report.md", best_epoch: bool = True) -> str:
    """Calls ``create_report.py`` on the given run directories, returns the markdown."""
    cmd = [sys.executable, "create_report.py", "--output", str(output)]
    if best_epoch:
        cmd.append("--best-epoch")
    cmd += [str(d) for d in run_dirs]
    subprocess.run(cmd, check=True, capture_output=True, text=True)
    return Path(output).read_text(encoding="utf-8")


