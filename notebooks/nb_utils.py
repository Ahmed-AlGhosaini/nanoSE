# Fixed categorical order -- assigned by series identity, never cycled.
PALETTE = [
    "#2a78d6",  # blue
    "#eb6834",  # orange
    "#1baf7a",  # aqua
    "#eda100",  # yellow
    "#e87ba4",  # magenta
    "#008300",  # green
    "#4a3aa7",  # violet
    "#e34948",  # red
]
GRID = "#dcdcd8"
INK = "#0b0b0b"
INK_SOFT = "#52514e"


def style_axes(ax, title: str = "", xlabel: str = "", ylabel: str = ""):
    """Recessive grid and axes, text in ink tokens rather than series colors."""
    ax.set_title(title, color=INK, fontsize=12, loc="left", pad=10)
    ax.set_xlabel(xlabel, color=INK_SOFT, fontsize=10)
    ax.set_ylabel(ylabel, color=INK_SOFT, fontsize=10)
    ax.grid(True, color=GRID, linewidth=0.8, alpha=0.9)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=INK_SOFT, labelsize=9)
    return ax


def plot_curves(
    run_dirs,
    labels=None,
    metric: str = "val_si_sdr",
    x: str = "epoch",
    title: str | None = None,
    ylabel: str | None = None,
    ax=None,
):
    """
    Overlays one line per run. Series colors follow the run's position in the
    fixed palette; a legend is always drawn when more than one run is shown.
    """
    import matplotlib.pyplot as plt

    labels = list(labels) if labels else [Path(d).name for d in run_dirs]
    if len(run_dirs) > len(PALETTE):
        raise ValueError(
            f"{len(run_dirs)} runs exceeds the {len(PALETTE)}-slot categorical palette; "
            "split the comparison into small multiples instead."
        )
    if ax is None:
        _, ax = plt.subplots(figsize=(8, 4.5))

    for index, (run_dir, label) in enumerate(zip(run_dirs, labels)):
        frame = load_metrics(run_dir)
        if frame.empty or metric not in frame:
            continue
        color = PALETTE[index]
        ax.plot(
            frame[x],
            frame[metric],
            color=color,
            linewidth=2,
            marker="o",
            markersize=4.5,
            label=label,
        )
        # Direct label on the final point (identity is never color-alone)
        if len(run_dirs) <= 4 and len(frame):
            last = frame.iloc[-1]
            ax.annotate(
                label,
                (last[x], last[metric]),
                textcoords="offset points",
                xytext=(6, 0),
                color=INK_SOFT,
                fontsize=9,
                va="center",
            )

    pretty = {
        "val_si_sdr": "Validation SI-SDR (dB)",
        "pesq": "PESQ",
        "estoi": "eSTOI",
        "dnsmos": "DNSMOS (OVRL)",
        "loss": "Training loss",
        "train_si_sdr": "Training SI-SDR (dB)",
    }
    xpretty = {"epoch": "Epoch", "cumulative_time_min": "Wall-clock training time (min)"}
    style_axes(
        ax,
        title=title or pretty.get(metric, metric),
        xlabel=xpretty.get(x, x),
        ylabel=ylabel or pretty.get(metric, metric),
    )
    if len(run_dirs) > 1:
        ax.legend(frameon=False, fontsize=9, labelcolor=INK_SOFT)
    return ax


def plot_bars(labels, values, title: str = "", ylabel: str = "", baseline=None, ax=None):
    """Ranked horizontal bars -- the form for comparing a magnitude across runs."""
    import matplotlib.pyplot as plt

    if ax is None:
        _, ax = plt.subplots(figsize=(8, 0.45 * len(labels) + 1.8))
    order = sorted(range(len(values)), key=lambda i: values[i])
    labels = [labels[i] for i in order]
    values = [values[i] for i in order]

    ax.barh(labels, values, color=PALETTE[0], height=0.62)
    if baseline is not None:
        ax.axvline(baseline, color=INK_SOFT, linewidth=1.2, linestyle="--")
        ax.annotate(
            "baseline",
            (baseline, len(labels) - 0.4),
            color=INK_SOFT,
            fontsize=9,
            xytext=(4, 0),
            textcoords="offset points",
        )
    for index, value in enumerate(values):
        ax.annotate(
            f"{value:.2f}",
            (value, index),
            xytext=(4, 0),
            textcoords="offset points",
            va="center",
            color=INK_SOFT,
            fontsize=9,
        )
    style_axes(ax, title=title, xlabel=ylabel)
    ax.grid(axis="y", visible=False)
    ax.margins(x=0.12)
    return ax
